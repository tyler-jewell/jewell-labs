#!/usr/bin/env bash
# Non-interactive: install Hermes into this repo, wire compare harness, run a sample.
#
# Usage (from anywhere):
#   bash evals/harness_compare/install_and_compare.sh
#   bash evals/harness_compare/install_and_compare.sh --install-only
#   bash evals/harness_compare/install_and_compare.sh --sample-only
#   bash evals/harness_compare/install_and_compare.sh --tasks coding_fix_bug,closed_form_ratio
#
# Layout (all under the monorepo, gitignored):
#   evals/harness_compare/vendor/hermes-home/   # HERMES_HOME (config, sessions)
#   evals/harness_compare/vendor/hermes-agent/  # code + venv
#   evals/harness_compare/vendor/bin/hermes     # stable launcher symlink
#
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HC="$ROOT/evals/harness_compare"
VENDOR="$HC/vendor"
HERMES_HOME="$VENDOR/hermes-home"
INSTALL_DIR="$VENDOR/hermes-agent"
BIN_DIR="$VENDOR/bin"
HERMES_BIN="$BIN_DIR/hermes"
INSTALLER_URL="${HERMES_INSTALLER_URL:-https://hermes-agent.nousresearch.com/install.sh}"

# Local OpenAI-compatible endpoint (llama-server). Overridable.
# Hermes needs ~18k+ tokens for its system prompt alone; default to compare
# port 8091 (see ensure_compare_llama) rather than a 2k jewell chat server.
LLAMA_BASE="${COMPARE_LLAMA:-http://127.0.0.1:8091}"
LLAMA_MODEL="${COMPARE_LLAMA_MODEL:-}"  # empty = probe /v1/models
# Declared context must be ≥64k for Hermes validation; real server may be smaller.
HERMES_DECLARED_CTX="${HERMES_DECLARED_CTX:-65536}"
COMPARE_MODEL_PATH="${COMPARE_MODEL_PATH:-/Users/studio/.llama/models/Qwen3-4B-Instruct-2507-Q8_0.gguf}"
COMPARE_CTX="${COMPARE_CTX:-32768}"
COMPARE_PORT="${COMPARE_PORT:-8091}"
JEWELL_BASE="${JEWELL_BASE:-http://127.0.0.1:3000}"
START_LLAMA=1

DO_INSTALL=1
DO_SAMPLE=1
TASKS="${COMPARE_TASKS:-coding_fix_bug,closed_form_ratio,agent_os_introspection}"
N_RUNS="${COMPARE_N_RUNS:-1}"
FORCE_REINSTALL=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --install-only) DO_SAMPLE=0; shift ;;
    --sample-only)  DO_INSTALL=0; shift ;;
    --force)        FORCE_REINSTALL=1; shift ;;
    --tasks)        TASKS="$2"; shift 2 ;;
    --n-runs)       N_RUNS="$2"; shift 2 ;;
    --no-start-llama) START_LLAMA=0; shift ;;
    -h|--help)
      sed -n '2,20p' "$0"
      exit 0
      ;;
    *)
      echo "Unknown arg: $1" >&2
      exit 2
      ;;
  esac
done

log()  { printf '==> %s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

require_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "missing required command: $1"
}

probe_llama_model() {
  local json id
  json="$(curl -fsS --max-time 5 "${LLAMA_BASE}/v1/models" 2>/dev/null || true)"
  if [[ -z "$json" ]]; then
    echo ""
    return 0
  fi
  # Prefer .data[0].id then .models[0].name
  # Prefer jq when available; else a tiny pure-bash/sed scrape (no first-party Python).
  if command -v jq >/dev/null 2>&1; then
    id="$(printf '%s' "$json" | jq -r '
      if (.data | type) == "array" and (.data | length) > 0 then .data[0].id // empty
      elif (.models | type) == "array" and (.models | length) > 0 then (.models[0].name // .models[0].model // empty)
      else empty end
    ' 2>/dev/null || true)"
  else
    id="$(printf '%s' "$json" | sed -n 's/.*"id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
  fi
  echo "$id"
}

ensure_compare_llama() {
  # Hermes system+tools prompt alone is ~18k tokens. A 2k jewell chat server is
  # not enough. Start/reuse a dedicated compare endpoint when missing.
  if curl -fsS --max-time 2 "${LLAMA_BASE}/v1/models" >/dev/null 2>&1; then
    log "llama-server already up at $LLAMA_BASE"
    return 0
  fi
  if [[ "$START_LLAMA" -ne 1 ]]; then
    warn "No llama at $LLAMA_BASE and --no-start-llama set"
    return 0
  fi
  if ! command -v llama-server >/dev/null 2>&1; then
    warn "llama-server not on PATH; cannot auto-start"
    return 0
  fi
  if [[ ! -f "$COMPARE_MODEL_PATH" ]]; then
    warn "COMPARE_MODEL_PATH missing: $COMPARE_MODEL_PATH"
    return 0
  fi
  log "Starting compare llama-server on port $COMPARE_PORT (ctx=$COMPARE_CTX)"
  log "  model=$COMPARE_MODEL_PATH"
  nohup llama-server \
    -m "$COMPARE_MODEL_PATH" \
    --host 127.0.0.1 --port "$COMPARE_PORT" \
    -c "$COMPARE_CTX" -np 1 --ctx-checkpoints 0 \
    >"$VENDOR/llama-compare.log" 2>&1 &
  echo $! >"$VENDOR/llama-compare.pid"
  local i
  for i in $(seq 1 90); do
    if curl -fsS --max-time 2 "http://127.0.0.1:${COMPARE_PORT}/v1/models" >/dev/null 2>&1; then
      log "compare llama-server ready (pid $(cat "$VENDOR/llama-compare.pid"))"
      LLAMA_BASE="http://127.0.0.1:${COMPARE_PORT}"
      return 0
    fi
    sleep 1
  done
  warn "llama-server failed to become ready; see $VENDOR/llama-compare.log"
}

write_hermes_config() {
  local model="$1"
  mkdir -p "$HERMES_HOME"
  # Secrets
  cat >"$HERMES_HOME/.env" <<EOF
# Generated by install_and_compare.sh — do not commit
OPENAI_API_KEY=local-not-required
OPENAI_BASE_URL=${LLAMA_BASE}/v1
EOF
  chmod 600 "$HERMES_HOME/.env"

  # Hermes enforces a *declared* minimum of 64k context. Real local n_ctx may be
  # lower (we default compare server to 32k which fits the ~18k tool prompt).
  cat >"$HERMES_HOME/config.yaml" <<EOF
# Generated by install_and_compare.sh for jewell harness_compare (local llama.cpp)
model:
  default: "${model}"
  provider: "custom"
  base_url: "${LLAMA_BASE}/v1"
  api_key: "local-not-required"
  context_length: ${HERMES_DECLARED_CTX}
  max_tokens: 1024

auxiliary:
  compression:
    provider: "main"
    context_length: ${HERMES_DECLARED_CTX}

terminal:
  backend: local

agent:
  api_max_retries: 1
EOF
  log "Wrote $HERMES_HOME/config.yaml (model=${model}, base=${LLAMA_BASE}/v1, declared_ctx=${HERMES_DECLARED_CTX})"
}

install_hermes() {
  require_cmd curl
  require_cmd git
  require_cmd python3
  require_cmd bash

  mkdir -p "$VENDOR" "$BIN_DIR"

  if [[ -x "$INSTALL_DIR/venv/bin/hermes" || -x "$INSTALL_DIR/venv/bin/python" ]]; then
    if [[ "$FORCE_REINSTALL" -eq 0 ]]; then
      log "Hermes already present at $INSTALL_DIR (use --force to reinstall)"
    else
      log "Removing previous vendor install (--force)"
      rm -rf "$INSTALL_DIR" "$HERMES_HOME"
    fi
  fi

  if [[ ! -d "$INSTALL_DIR/.git" && ! -x "$INSTALL_DIR/venv/bin/hermes" ]]; then
    log "Downloading Hermes installer…"
    local tmp
    tmp="$(mktemp)"
    curl -fsSL "$INSTALLER_URL" -o "$tmp"

    log "Installing non-interactively into $INSTALL_DIR"
    log "  HERMES_HOME=$HERMES_HOME"
    # Official installer flags: --dir, --hermes-home, --skip-setup, --skip-browser, --non-interactive
    bash "$tmp" \
      --dir "$INSTALL_DIR" \
      --hermes-home "$HERMES_HOME" \
      --skip-setup \
      --skip-browser \
      --non-interactive \
      --no-skills
    rm -f "$tmp"
  fi

  # Resolve hermes binary
  local real_bin=""
  for cand in \
    "$INSTALL_DIR/venv/bin/hermes" \
    "$INSTALL_DIR/bin/hermes" \
    "$HERMES_HOME/bin/hermes"
  do
    if [[ -x "$cand" ]]; then
      real_bin="$cand"
      break
    fi
  done
  # Some installs only have a python -m entry; try common paths
  if [[ -z "$real_bin" ]]; then
    if [[ -x "$INSTALL_DIR/venv/bin/python" ]]; then
      # Create a thin launcher
      cat >"$HERMES_BIN" <<'LAUNCH'
#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
export HERMES_HOME="${HERMES_HOME:-$ROOT/hermes-home}"
# Prefer installed package console script if present after first import path fix
if [[ -x "$ROOT/hermes-agent/venv/bin/hermes" ]]; then
  exec "$ROOT/hermes-agent/venv/bin/hermes" "$@"
fi
exec "$ROOT/hermes-agent/venv/bin/python" -m hermes_cli "$@"
LAUNCH
      # fix paths in launcher - rewrite with actual layout
      cat >"$HERMES_BIN" <<LAUNCH
#!/usr/bin/env bash
set -euo pipefail
export HERMES_HOME="${HERMES_HOME}"
if [[ -x "${INSTALL_DIR}/venv/bin/hermes" ]]; then
  exec "${INSTALL_DIR}/venv/bin/hermes" "\$@"
fi
if [[ -x "${INSTALL_DIR}/venv/bin/python" ]]; then
  exec "${INSTALL_DIR}/venv/bin/python" -m hermes_cli "\$@"
fi
echo "hermes binary not found under ${INSTALL_DIR}" >&2
exit 127
LAUNCH
      chmod +x "$HERMES_BIN"
      real_bin="$HERMES_BIN"
    fi
  else
    ln -sfn "$real_bin" "$HERMES_BIN"
  fi

  [[ -n "$real_bin" && -e "$HERMES_BIN" ]] || die "could not locate hermes binary after install"
  log "Hermes launcher: $HERMES_BIN -> $(readlink "$HERMES_BIN" 2>/dev/null || echo "$real_bin")"

  ensure_compare_llama
  # Model for config
  local model="$LLAMA_MODEL"
  if [[ -z "$model" ]]; then
    model="$(probe_llama_model)"
  fi
  if [[ -z "$model" ]]; then
    warn "No model at ${LLAMA_BASE}/v1/models — writing placeholder config (hermes runs will fail until endpoint is up)"
    model="local"
  fi
  write_hermes_config "$model"

  # Smoke: hermes --help should work
  export HERMES_HOME
  if ! HERMES_HOME="$HERMES_HOME" "$HERMES_BIN" --help >/dev/null 2>&1; then
    # try version / doctor
    if ! HERMES_HOME="$HERMES_HOME" "$HERMES_BIN" version 2>/dev/null; then
      warn "hermes --help failed; dumping which files exist:"
      ls -la "$INSTALL_DIR" 2>/dev/null | head -30 || true
      ls -la "$INSTALL_DIR/venv/bin" 2>/dev/null | head -40 || true
    fi
  fi
  log "Install complete."
}

run_sample() {
  [[ -x "$HERMES_BIN" || -e "$HERMES_BIN" ]] || die "Hermes not installed. Run without --sample-only first."

  export HERMES_HOME
  export HERMES_BIN
  export JEWELL_BASE
  export COMPARE_LLAMA="$LLAMA_BASE"

  local run_id
  run_id="sample-$(date -u +%Y%m%dT%H%M%SZ)"
  log "Running sample compare run_id=$run_id"
  log "  harnesses: dry,jewell,hermes"
  log "  tasks: $TASKS"
  log "  HERMES_BIN=$HERMES_BIN"
  log "  HERMES_HOME=$HERMES_HOME"
  log "  JEWELL_BASE=$JEWELL_BASE"
  log "  LLAMA=$LLAMA_BASE"

  ensure_compare_llama
  # rewrite config in case LLAMA_BASE changed after ensure
  local model="$LLAMA_MODEL"
  [[ -z "$model" ]] && model="$(probe_llama_model)"
  [[ -z "$model" ]] && model="local"
  write_hermes_config "$model"

  # Preflight
  if curl -fsS --max-time 2 "$JEWELL_BASE/healthz" >/dev/null 2>&1; then
    log "jewell healthz: ok"
  else
    warn "jewell not reachable at $JEWELL_BASE — agent_os host gates still work (cargo); chat tasks may error"
  fi
  if curl -fsS --max-time 2 "$LLAMA_BASE/v1/models" >/dev/null 2>&1; then
    log "llama-server: ok ($LLAMA_BASE)"
  else
    warn "llama-server not reachable at $LLAMA_BASE — closed_form/hermes coding may fail"
  fi

  log "Running Rust eval_compare (not Python)…"
  (
    cd "$ROOT/rust-agent"
    export HERMES_HOME HERMES_BIN JEWELL_BASE COMPARE_LLAMA
    local n_arg=()
    if [[ -n "${N_RUNS}" ]]; then n_arg=(--n-runs "$N_RUNS"); fi
    cargo run -q --bin eval_compare -- \
      --harnesses dry,jewell,hermes \
      --tasks "$TASKS" \
      "${n_arg[@]}" \
      --run-id "$run_id"
  )

  log "Sample finished. Report: $ROOT/evals/runs/${run_id}.json"
  if [[ -f "$ROOT/evals/runs/${run_id}.json" ]]; then
    if command -v jq >/dev/null 2>&1; then
      jq -r '
        "kind \(.kind // "?") items \((.items // []) | length)",
        ((.summary.harnesses // {}) | to_entries[] |
          "  \(.key): avg=\(.value.avg_score) solid=\(.value.solid_base) skip=\(.value.n_skip)"),
        ((.items // [])[] |
          "  [\(.status)] \(.harness)/\(.task_id) score=\(.score)")
      ' "$ROOT/evals/runs/${run_id}.json" || true
    else
      log "Report written (install jq to pretty-print summary)."
    fi
  fi
}

# ── main ────────────────────────────────────────────────────────────────────
log "repo root: $ROOT"
log "vendor:    $VENDOR"

if [[ "$DO_INSTALL" -eq 1 ]]; then
  install_hermes
fi
if [[ "$DO_SAMPLE" -eq 1 ]]; then
  run_sample
fi
log "Done."
